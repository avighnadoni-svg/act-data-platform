USE DATABASE ACT_DB;
USE SCHEMA CONTROL;

CREATE TABLE IF NOT EXISTS PIPELINE_ALERT
(
    ALERT_ID            VARCHAR          NOT NULL,
    DAG_ID              VARCHAR,
    DAG_RUN_ID          VARCHAR,
    TASK_ID             VARCHAR,
    MAP_INDEX           NUMBER,
    ALERT_TYPE          VARCHAR          NOT NULL,
    SEVERITY            VARCHAR          NOT NULL,
    STATUS              VARCHAR          NOT NULL,
    ERROR_MESSAGE       VARCHAR,
    LOGICAL_DATE        TIMESTAMP_TZ,
    CREATED_AT          TIMESTAMP_LTZ    DEFAULT CURRENT_TIMESTAMP(),

    CONSTRAINT PK_PIPELINE_ALERT
        PRIMARY KEY (ALERT_ID)
);

COMMENT ON TABLE PIPELINE_ALERT IS
'Operational alerts generated by ACT Airflow pipeline failures';

COMMENT ON COLUMN PIPELINE_ALERT.ALERT_TYPE IS
'Failure category such as TASK_FAILURE, DBT_FAILURE or RECONCILIATION_FAILURE';

COMMENT ON COLUMN PIPELINE_ALERT.SEVERITY IS
'Operational severity such as ERROR or CRITICAL';

COMMENT ON COLUMN PIPELINE_ALERT.STATUS IS
'Alert lifecycle status such as OPEN or RESOLVED';